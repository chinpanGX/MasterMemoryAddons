using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using MasterMemory.Addons.Tools.Common;
using Xunit;

namespace MasterMemory.Addons.Tools.Tests.Common;

public class OutputDirectoryTests
{
    private static ToolsConfig Config(TempDirectory temp, string definitions, params (string Name, string Source)[] outputs)
    {
        var list = new List<OutputConfig>();
        foreach (var (name, source) in outputs)
        {
            list.Add(new OutputConfig(name, GenerationTarget.Client, temp.Combine(source)));
        }

        return new ToolsConfig(temp.Combine("config"), temp.Combine(definitions), list);
    }

    [Fact]
    public void Validate_ReturnsNoProblem_ForSeparateDirectories()
    {
        // 検証: 定義とも互いとも重ならない出力先を確認する
        // 期待: 問題なし
        using var temp = new TempDirectory();
        var config = Config(temp, "config/Definitions", ("unity", "Client/Generated"), ("api", "Server/Generated"));

        Assert.Empty(OutputDirectory.Validate(config));
    }

    [Theory]
    [InlineData("config")]                    // 設定ファイルのディレクトリそのもの
    [InlineData(".")]                         // 設定ファイルのディレクトリの上位
    [InlineData("config/Definitions")]        // definitions と同じ
    [InlineData("config/Definitions/Out")]    // definitions の下
    public void Validate_ReturnsProblem_WhenSourceContainsProtectedDirectory(string source)
    {
        // 検証: 設定ファイルや定義のディレクトリを含む(または定義の中にある)出力先を確認する
        // 期待: 問題として返す(丸ごと削除すると消えてしまうため)
        using var temp = new TempDirectory();
        var config = Config(temp, "config/Definitions", ("unity", source));

        Assert.NotEmpty(OutputDirectory.Validate(config));
    }

    [Fact]
    public void Validate_ReturnsProblem_WhenSourceIsAboveDefinitions()
    {
        // 検証: 定義のディレクトリの上位を出力先にする
        // 期待: 問題として返す
        using var temp = new TempDirectory();
        var config = Config(temp, "data/Definitions", ("unity", "data"));

        Assert.NotEmpty(OutputDirectory.Validate(config));
    }

    [Theory]
    [InlineData("data")]          // csv の上位
    [InlineData("data/csv")]      // csv と同じ
    [InlineData("data/csv/out")]  // csv の下
    public void Validate_ReturnsProblem_WhenSourceOverlapsCsv(string source)
    {
        // 検証: csv のディレクトリと重なる出力先を確認する
        // 期待: 問題として返す(丸ごと削除すると CSV が消えてしまうため)
        using var temp = new TempDirectory();
        var config = Config(temp, "config/Definitions", ("unity", source)) with { Csv = temp.Combine("data/csv") };

        Assert.NotEmpty(OutputDirectory.Validate(config));
    }

    [Fact]
    public void Validate_ReturnsNoProblem_WhenSourceIsBesideCsv()
    {
        // 検証: csv のディレクトリの隣を出力先にする
        // 期待: 問題なし
        using var temp = new TempDirectory();
        var config = Config(temp, "config/Definitions", ("unity", "data/out")) with { Csv = temp.Combine("data/csv") };

        Assert.Empty(OutputDirectory.Validate(config));
    }

    [Fact]
    public void Validate_ReturnsProblem_WhenSourceIsRoot()
    {
        // 検証: ドライブのルートを出力先にする
        // 期待: 問題として返す
        using var temp = new TempDirectory();
        var root = Path.GetPathRoot(temp.Path)!;
        var config = new ToolsConfig(
            temp.Combine("config"),
            temp.Combine("config/Definitions"),
            new[] { new OutputConfig("unity", GenerationTarget.Client, root) });

        Assert.NotEmpty(OutputDirectory.Validate(config));
    }

    [Theory]
    [InlineData("out/client", "out/client")]
    [InlineData("out", "out/server")]
    public void Validate_ReturnsProblem_WhenSourcesOverlap(string first, string second)
    {
        // 検証: 同じ、または親子関係にある出力先を2つ指定する
        // 期待: 問題として返す
        using var temp = new TempDirectory();
        var config = Config(temp, "config/Definitions", ("a", first), ("b", second));

        Assert.NotEmpty(OutputDirectory.Validate(config));
    }

    [Fact]
    public void Validate_DoesNotTreatPrefixNameAsInside()
    {
        // 検証: 名前の先頭だけが同じ出力先(out/client と out/client2)を指定する
        // 期待: 重なりとはみなさず、問題なし
        using var temp = new TempDirectory();

        // "out/client" と "out/client2" は重なっていない
        var config = Config(temp, "config/Definitions", ("a", "out/client"), ("b", "out/client2"));

        Assert.Empty(OutputDirectory.Validate(config));
    }

    [Fact]
    public void Replace_DeletesEverythingInDirectory_AndWritesFiles()
    {
        // 検証: 手書きのファイル・なくなるファイルの .meta・サブディレクトリがある出力先を入れ替える
        // 期待: 中身はすべて消え、渡したファイルだけが残る
        using var temp = new TempDirectory();
        var target = temp.Combine("out/client");
        temp.Write("out/client/Old.cs", "// <auto-generated>");
        temp.Write("out/client/Handwritten.cs", "// 手書き");
        temp.Write("out/client/Old.cs.meta", "meta");
        temp.Write("out/client/Sub/Nested.cs", "nested");

        OutputDirectory.Replace(target, new[]
        {
            new GeneratedFile("Item.cs", "item"),
            new GeneratedFile(Path.Combine("Tables", "Skill.cs"), "skill"),
        });

        var files = Directory.GetFiles(target, "*", SearchOption.AllDirectories);
        Assert.Equal(2, files.Length);
        Assert.Equal("item", File.ReadAllText(Path.Combine(target, "Item.cs")));
        Assert.Equal("skill", File.ReadAllText(Path.Combine(target, "Tables", "Skill.cs")));
        Assert.False(Directory.Exists(Path.Combine(target, "Sub")));
    }

    [Fact]
    public void Replace_KeepsMetaFiles_OfGeneratedFilesAndFolders()
    {
        // 検証: 生成するファイル・フォルダの .meta と、なくなるファイル・フォルダの .meta がある出力先を入れ替える(review の R3)
        // 期待: 生成するファイル(Item.cs、Tables/Skill.cs)とフォルダ(Tables)の .meta は中身ごと残り、ほかの .meta は消える。
        //       .meta だけが残っていた、なくなるフォルダ(Sub)も消える
        using var temp = new TempDirectory();
        var target = temp.Combine("out/client");
        temp.Write("out/client/Item.cs", "old");
        temp.Write("out/client/Item.cs.meta", "guid: item");
        temp.Write("out/client/Tables.meta", "guid: tables");
        temp.Write("out/client/Tables/Skill.cs.meta", "guid: skill");
        temp.Write("out/client/Old.cs.meta", "guid: old");
        temp.Write("out/client/Sub.meta", "guid: sub");
        temp.Write("out/client/Sub/Nested.cs.meta", "guid: nested");

        OutputDirectory.Replace(target, new[]
        {
            new GeneratedFile("Item.cs", "item"),
            new GeneratedFile(Path.Combine("Tables", "Skill.cs"), "skill"),
        });

        var files = Directory.GetFiles(target, "*", SearchOption.AllDirectories)
            .Select(f => Path.GetRelativePath(target, f).Replace(Path.DirectorySeparatorChar, '/'))
            .OrderBy(f => f, StringComparer.Ordinal);
        Assert.Equal(new[] { "Item.cs", "Item.cs.meta", "Tables.meta", "Tables/Skill.cs", "Tables/Skill.cs.meta" }, files);
        Assert.Equal("item", File.ReadAllText(Path.Combine(target, "Item.cs")));
        Assert.Equal("guid: item", File.ReadAllText(Path.Combine(target, "Item.cs.meta")));
        Assert.Equal("guid: skill", File.ReadAllText(Path.Combine(target, "Tables", "Skill.cs.meta")));
        Assert.False(Directory.Exists(Path.Combine(target, "Sub")));
    }

    [Fact]
    public void Replace_DoesNotTouchFilesOutsideDirectory()
    {
        // 検証: 隣や親のディレクトリにファイルがある状態で出力先を入れ替える
        // 期待: 出力先の外のファイルは残る
        using var temp = new TempDirectory();
        var sibling = temp.Write("out/client2/Handwritten.cs", "// 手書き");
        var parent = temp.Write("out/Readme.txt", "readme");

        OutputDirectory.Replace(temp.Combine("out/client"), new[] { new GeneratedFile("Item.cs", "item") });

        Assert.True(File.Exists(sibling));
        Assert.True(File.Exists(parent));
    }

    [Fact]
    public void Replace_CreatesDirectory_WhenMissing()
    {
        // 検証: 存在しない出力先を入れ替える
        // 期待: ディレクトリが作られ、ファイルが書き込まれる
        using var temp = new TempDirectory();
        var target = temp.Combine("new/client");

        OutputDirectory.Replace(target, new[] { new GeneratedFile("Item.cs", "item") });

        Assert.True(File.Exists(Path.Combine(target, "Item.cs")));
    }
}
