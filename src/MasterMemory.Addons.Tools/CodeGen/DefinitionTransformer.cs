using System;
using System.Linq;
using MasterMemory.Addons.Tools.Common;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace MasterMemory.Addons.Tools.CodeGen;

/// <summary>定義ソース1ファイル分(パースした構文木)を、指定した対象向けのソースに変換する。</summary>
public static class DefinitionTransformer
{
    /// <summary>
    /// 変換した結果を返す。型が1つも残らない場合は null を返す。
    /// 構文エラーがある、またはテーブルの型が class でない(record・struct など)場合は <see cref="DefinitionParseException"/> を投げる。
    /// </summary>
    public static string? Transform(SyntaxTree tree, GenerationTarget target)
    {
        var errors = tree.GetDiagnostics()
            .Where(d => d.Severity == DiagnosticSeverity.Error)
            .Select(d => d.ToString())
            .ToList();
        if (errors.Count > 0)
        {
            throw new DefinitionParseException(string.Join(Environment.NewLine, errors));
        }

        var root = tree.GetRoot();

        // テーブルの型は class だけ(Id で同じ行とみなす使い方を前提にするため。record の値の比べ方とは合わない)
        var tableErrors = root.DescendantNodes().OfType<TypeDeclarationSyntax>()
            .Select(t => (Type: t, Message: DefinitionSchemaReader.NonClassTableMessage(t)))
            .Where(e => e.Message is not null)
            .Select(e =>
            {
                var position = e.Type.Identifier.GetLocation().GetLineSpan().StartLinePosition;
                return $"({position.Line + 1},{position.Character + 1}): {e.Type.Identifier.ValueText}: {e.Message}";
            })
            .ToList();
        if (tableErrors.Count > 0)
        {
            throw new DefinitionParseException(string.Join(Environment.NewLine, tableErrors));
        }

        var rewritten = new TargetFilterRewriter(target).Visit(root)
            ?? throw new InvalidOperationException("構文木の書き換えに失敗しました。");

        if (!rewritten.DescendantNodes().OfType<BaseTypeDeclarationSyntax>().Any())
        {
            return null;
        }

        var header =
            "// <auto-generated>" + "\n" +
            "// Generated by MasterMemory.Addons.Tools. Do not edit." + "\n" +
            $"// Target: {target}" + "\n" +
            "// </auto-generated>" + "\n";

        return header + rewritten.NormalizeWhitespace().ToFullString() + "\n";
    }
}
