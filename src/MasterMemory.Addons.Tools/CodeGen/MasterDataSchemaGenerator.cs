using System;
using System.Collections.Generic;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using MasterMemory.Addons.Tools.Common;
using Microsoft.CodeAnalysis.CSharp;

namespace MasterMemory.Addons.Tools.CodeGen;

/// <summary>
/// 生成ソースからスキーマのハッシュを計算し、MasterDataSchema のソースを作る。client / server の両方の出力先に置く。
/// client では、このハッシュが暗号化の鍵も兼ねるので、外(バイナリのヘッダやマニフェスト)にはスキーマの ID だけを出す。
/// 形式は docs/design/pipeline.md の「スキーマのハッシュ」。
/// </summary>
public static class MasterDataSchemaGenerator
{
    public const string FileName = "MasterDataSchema.cs";

    /// <summary>生成する型の名前。</summary>
    public const string TypeName = "MasterDataSchema";

    /// <summary>
    /// コメントと空白を除いたトークン列の SHA-256(16進の小文字)を返す。
    /// ファイル名や、ファイルの並び順には依存しない。
    /// </summary>
    public static string Compute(IEnumerable<GeneratedFile> files)
    {
        var options = new CSharpParseOptions(LanguageVersion.Latest);
        var normalized = files
            .Select(f => string.Join("\n", CSharpSyntaxTree.ParseText(f.Text, options).GetRoot().DescendantTokens().Select(t => t.Text)))
            .OrderBy(t => t, StringComparer.Ordinal);

        var builder = new StringBuilder();
        foreach (var text in normalized)
        {
            builder.Append(text).Append('\0');
        }

        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(builder.ToString()));
        return Convert.ToHexString(hash).ToLowerInvariant();
    }

    /// <summary>MasterDataSchema.cs の内容を返す(Unity の C# 9 で通る書き方)。</summary>
    public static string Generate(string @namespace, string hash)
    {
        return
            "// <auto-generated>" + "\n" +
            "// Generated by MasterMemory.Addons.Tools. Do not edit." + "\n" +
            "// </auto-generated>" + "\n" +
            $"namespace {@namespace}" + "\n" +
            "{" + "\n" +
            "    /// <summary>" + "\n" +
            "    /// マスターデータのスキーマのハッシュ。この出力先の生成ソースから計算した値で、定義が変わると変わる。" + "\n" +
            "    /// バイナリを読むときは MasterDataBinary.Read(bytes, MasterDataSchema.Hash) に渡す(暗号化の鍵も兼ねる)。" + "\n" +
            "    /// 鍵なので、ログやサーバーへの送信などで外に出さない。外に出すときは MasterDataBinary.ComputeSchemaId(Hash) を使う。" + "\n" +
            "    /// </summary>" + "\n" +
            "    public static class MasterDataSchema" + "\n" +
            "    {" + "\n" +
            $"        public const string Hash = \"{hash}\";" + "\n" +
            "    }" + "\n" +
            "}" + "\n";
    }
}
